import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';
import { emptyState, recordAnswer, updateWord, deleteWord, restoreWord, resetAllCards } from '../dist/engine.js';
import { WORDS } from '../dist/data.js';

test('actual PostgreSQL migration isolates users and rejects stale writes', async () => {
  const db = new PGlite();
  const userA = '11111111-1111-4111-8111-111111111111';
  const userB = '22222222-2222-4222-8222-222222222222';
  try {
    await db.exec(`
      create role anon nologin;
      create role authenticated nologin;
      create schema auth;
      create table auth.users(id uuid primary key);
      create function auth.uid() returns uuid language sql stable as
        'select nullif(current_setting(''request.jwt.claim.sub'', true), '''')::uuid';
      grant usage on schema auth, public to authenticated, anon;
      grant execute on function auth.uid() to authenticated, anon;
      insert into auth.users values ('${userA}'), ('${userB}');
    `);
    const migration = await readFile(new URL('../supabase/migrations/202610270001_progress.sql', import.meta.url), 'utf8');
    await db.exec(migration);
    // Applying the same migration twice must not widen access or destroy rows.
    await db.exec(migration);
    const customMigration = await readFile(new URL('../supabase/migrations/20261027163609_protect_custom_vocabulary.sql', import.meta.url), 'utf8');
    await db.exec(customMigration);
    await db.exec(customMigration);
    const libraryMigration = await readFile(new URL('../supabase/migrations/20261027171520_empty_personal_libraries.sql', import.meta.url), 'utf8');
    await db.exec(libraryMigration);
    await db.exec(libraryMigration);
    const editableMigration = await readFile(new URL('../supabase/migrations/20261027181806_editable_vocabulary.sql', import.meta.url), 'utf8');
    await db.exec(editableMigration);
    await db.exec(editableMigration);
    const resetMigration = await readFile(new URL('../supabase/migrations/20261028083601_reset_card_reviews.sql', import.meta.url), 'utf8');
    await db.exec(resetMigration);
    await db.exec(resetMigration);
    // A has a pre-existing legacy library; B is a brand-new account.
    await db.query('insert into public.santa_progress(user_id) values ($1)', [userA]);
    await db.exec('set role anon');
    await assert.rejects(db.query('select * from public.santa_progress'), /permission denied/);
    await assert.rejects(db.query('select public.sync_santa_progress($1,0,$2)', [userA, emptyState()]), /permission denied/);
    await db.exec('reset role; set role authenticated');
    await db.query("select set_config('request.jwt.claim.sub',$1,false)", [userA]);
    const stateA = emptyState(); recordAnswer(stateA, 23, true, 'quiz', 'test-A');
    let result = await db.query('select public.sync_santa_progress($1,0,$2) as result', [userA, stateA]);
    assert.equal(result.rows[0].result.applied, true);
    assert.equal(result.rows[0].result.revision, 1);
    result = await db.query('select public.sync_santa_progress($1,0,$2) as result', [userA, emptyState()]);
    assert.equal(result.rows[0].result.applied, false);
    assert.equal(result.rows[0].result.state.progress['23'].correct, 1);
    await assert.rejects(db.query('select public.sync_santa_progress($1,0,$2)', [userB, emptyState()]), /Authentication changed/);
    await assert.rejects(db.query('insert into public.santa_progress(user_id) values ($1)', [userB]), /row-level security/);
    await assert.rejects(db.query('select public.sync_santa_progress($1,null,$2)', [userA, stateA]), /Invalid revision/);
    await assert.rejects(db.query('select public.sync_santa_progress($1,1,$2)', [userA, {version:2,progress:{}}]), /Invalid progress payload/);
    stateA.customWords = [{id:1000001,word:'resilient',meaning:'有韌性的',pos:'',example:'',translation:'',note:''}];
    result = await db.query('select public.sync_santa_progress($1,1,$2) as result', [userA, stateA]);
    assert.equal(result.rows[0].result.state.customWords[0].word, 'resilient');
    const legacy = {version:2,progress:stateA.progress,history:stateA.history};
    await assert.rejects(db.query('select public.sync_santa_progress($1,2,$2)', [userA, legacy]), /Custom vocabulary is missing/);
    await assert.rejects(db.query('select public.sync_santa_progress($1,2,$2)', [userA, {...stateA,customWords:{}}]), /Invalid custom vocabulary/);
    const editedA = structuredClone(stateA);
    updateWord(editedA, WORDS, 1000001, { ...stateA.customWords[0], meaning: '能迅速恢復的' });
    await db.query('select public.sync_santa_progress($1,2,$2)', [userA, editedA]);
    await assert.rejects(db.query('select public.sync_santa_progress($1,3,$2)', [userA, stateA]), /Word changes are missing or stale/);
    await assert.rejects(db.query('select public.sync_santa_progress($1,3,$2)', [userA, {...editedA,wordChanges:[...editedA.wordChanges,...editedA.wordChanges]}]), /Invalid word changes/);
    const deletedA = structuredClone(editedA); deleteWord(deletedA, WORDS, 1000001);
    await db.query('select public.sync_santa_progress($1,3,$2)', [userA, deletedA]);
    const staleEdit = structuredClone(editedA); updateWord(staleEdit, WORDS, 1000001, {...stateA.customWords[0],meaning:'較晚的離線編輯'});
    await assert.rejects(db.query('select public.sync_santa_progress($1,4,$2)', [userA, staleEdit]), /Word changes are missing or stale/);
    const restoredA = structuredClone(deletedA); restoreWord(restoredA, WORDS, 1000001);
    await db.query('select public.sync_santa_progress($1,4,$2)', [userA, restoredA]);
    const resetA=structuredClone(restoredA); resetAllCards(resetA);
    result=await db.query('select public.sync_santa_progress($1,5,$2) as result',[userA,resetA]);
    assert.equal(result.rows[0].result.applied,true);
    assert.equal(result.rows[0].result.state.progress['23'].reviews,0);
    assert.equal(result.rows[0].result.state.history.length,restoredA.history.length);
    await assert.rejects(db.query('select public.sync_santa_progress($1,6,$2)',[userA,restoredA]),/Review reset is missing or stale/);
    await assert.rejects(db.query('select public.sync_santa_progress($1,6,$2)',[userA,{...resetA,reviewReset:null}]),/Invalid review reset/);
    const resetAgain=structuredClone(resetA); resetAllCards(resetAgain);
    await db.query('select public.sync_santa_progress($1,6,$2)',[userA,resetAgain]);
    await assert.rejects(db.query('select public.sync_santa_progress($1,7,$2)',[userA,resetA]),/Review reset is missing or stale/);
    await db.query("select set_config('request.jwt.claim.sub',$1,false)", [userB]);
    assert.equal((await db.query('select * from public.santa_progress')).rows.length, 0);
    const stateB = emptyState(false); recordAnswer(stateB, 47, false, 'quiz', 'test-B');
    await db.query('select public.sync_santa_progress($1,0,$2)', [userB, stateB]);
    await assert.rejects(db.query('select public.sync_santa_progress($1,1,$2)', [userB, {...stateB,includeBaseWords:true}]), /Library mode changed/);
    const oldClient = {...stateB}; delete oldClient.includeBaseWords;
    await assert.rejects(db.query('select public.sync_santa_progress($1,1,$2)', [userB, oldClient]), /Library mode changed/);
    const visible = (await db.query('select user_id,state from public.santa_progress')).rows;
    assert.equal(visible.length, 1);
    assert.equal(visible[0].user_id, userB);
    assert.equal(visible[0].state.progress['47'].wrong, 1);
    assert.equal((await db.query('update public.santa_progress set revision = 999 where user_id = $1 returning user_id', [userA])).rows.length, 0);
    await assert.rejects(db.query('delete from public.santa_progress where user_id = $1', [userB]), /permission denied/);
    await db.exec('reset role');
    assert.equal((await db.query('select count(*)::int as count from public.santa_progress')).rows[0].count, 2);
  } finally { await db.close(); }
});
